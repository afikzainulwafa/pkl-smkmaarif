-- Jalankan satu kali pada proyek Supabase baru. Tidak menghapus data.
begin;
create schema pkl_private;
revoke all on schema pkl_private from public, anon, authenticated;

create table pkl_private.admins (user_id uuid primary key references auth.users(id));
create table pkl_private.students (
 id bigint generated by default as identity primary key,
 nis text not null unique, nama_lengkap text not null, kelas text not null,
 jurusan text not null check(jurusan in ('TAB','TAV','TKJ','TKR')),
 email text not null, is_dummy boolean not null default false, active boolean not null default true
);
create unique index students_email_unique on pkl_private.students(lower(email));
create table pkl_private.places (
 id bigint primary key, source_no int, nama text not null, alamat text not null,
 wilayah text not null, jurusan text not null, pembimbing text not null, active boolean not null default true
);
create table pkl_private.periods (
 id bigint primary key, tahun_pelajaran text not null, gelombang int not null,
 registration_open boolean not null default false,
 change_mode text not null default 'admin_approval' check(change_mode in ('locked','self_service','admin_approval')),
 max_changes int not null default 1 check(max_changes>=0), deadline timestamptz,
 unique(tahun_pelajaran,gelombang)
);
create table pkl_private.quotas (
 id bigint primary key, tempat_id bigint not null references pkl_private.places(id),
 period_id bigint not null references pkl_private.periods(id),
 kuota int check(kuota>=0), terisi_import int check(terisi_import>=0),
 source_terisi text, source_sisa text, import_confirmed boolean not null default false,
 registration_open boolean not null default false, unique(tempat_id,period_id), unique(id,period_id)
);
create table pkl_private.registrations (
 id bigint generated always as identity primary key,
 student_id bigint not null references pkl_private.students(id),
 period_id bigint not null references pkl_private.periods(id), quota_id bigint not null,
 status text not null check(status in ('active','reset','cancelled')),
 change_count int not null default 0, created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 unique(student_id,period_id), foreign key(quota_id,period_id) references pkl_private.quotas(id,period_id)
);
create index registrations_quota on pkl_private.registrations(quota_id,status);
create table pkl_private.permissions (
 student_id bigint not null references pkl_private.students(id),
 period_id bigint not null references pkl_private.periods(id),
 change_override text not null default 'inherit' check(change_override in ('inherit','locked','self_service','admin_approval')),
 extra_changes int not null default 0 check(extra_changes>=0), primary key(student_id,period_id)
);
create table pkl_private.requests (
 id bigint generated always as identity primary key,
 registration_id bigint not null references pkl_private.registrations(id),
 student_id bigint not null references pkl_private.students(id), period_id bigint not null references pkl_private.periods(id),
 from_quota_id bigint not null references pkl_private.quotas(id), target_quota_id bigint not null,
 reason text not null, status text not null default 'pending' check(status in ('pending','approved','rejected','withdrawn')),
 created_at timestamptz not null default now(), decided_at timestamptz, decided_by uuid,
 foreign key(target_quota_id,period_id) references pkl_private.quotas(id,period_id)
);
create unique index one_pending_request on pkl_private.requests(registration_id) where status='pending';
create table pkl_private.audit (
 id bigint generated always as identity primary key, student_id bigint, period_id bigint,
 action text not null, actor_id uuid not null, old_quota_id bigint, new_quota_id bigint,
 reason text not null, detail jsonb not null default '{}'::jsonb, created_at timestamptz not null default now()
);

-- Defense in depth: tabel di schema non-exposed, tanpa direct grants, RLS aktif.
alter table pkl_private.admins enable row level security;
alter table pkl_private.students enable row level security;
alter table pkl_private.places enable row level security;
alter table pkl_private.periods enable row level security;
alter table pkl_private.quotas enable row level security;
alter table pkl_private.registrations enable row level security;
alter table pkl_private.permissions enable row level security;
alter table pkl_private.requests enable row level security;
alter table pkl_private.audit enable row level security;
revoke all on all tables in schema pkl_private from public, anon, authenticated;
revoke all on all sequences in schema pkl_private from public, anon, authenticated;

create function pkl_private.is_admin() returns boolean language sql stable security definer set search_path='' as $$
 select auth.uid() is not null and exists(select 1 from pkl_private.admins where user_id=auth.uid());
$$;
create function pkl_private.my_student_id() returns bigint language sql stable security definer set search_path='' as $$
 select s.id from pkl_private.students s join auth.users u on lower(s.email)=lower(u.email)
 where u.id=auth.uid() and u.email_confirmed_at is not null and s.active;
$$;
create function pkl_private.log_event(sid bigint,pid bigint,act text,oldq bigint,newq bigint,why text,details jsonb default '{}')
returns void language sql security definer set search_path='' as $$
 insert into pkl_private.audit(student_id,period_id,action,actor_id,old_quota_id,new_quota_id,reason,detail)
 values(sid,pid,act,auth.uid(),oldq,newq,why,details);
$$;

-- Seluruh mutasi mengikuti penguncian global, cukup untuk skala sekolah.
-- RPC atomik; kursi tidak dipesan oleh browser.
create function pkl_private.check_target(sid bigint,qid bigint,require_open boolean) returns void
language plpgsql security definer set search_path='' as $$
declare q pkl_private.quotas; s pkl_private.students; p pkl_private.places; pe pkl_private.periods; occupied int;
begin
 select * into s from pkl_private.students where id=sid;
 if not found or not s.active then raise exception 'Siswa tidak aktif atau tidak ditemukan.'; end if;
 select * into q from pkl_private.quotas where id=qid;
 if not found then raise exception 'Tempat/gelombang tidak ditemukan.'; end if;
 select * into p from pkl_private.places where id=q.tempat_id;
 select * into pe from pkl_private.periods where id=q.period_id;
 if p.jurusan<>s.jurusan or not p.active then raise exception 'Tempat tidak sesuai jurusan atau tidak aktif.'; end if;
 if require_open and (not pe.registration_open or (pe.deadline is not null and pe.deadline<=now())) then raise exception 'Pendaftaran ditutup atau melewati tenggat.'; end if;
 if not q.registration_open or not q.import_confirmed or q.kuota is null or q.terisi_import is null then raise exception 'Kuota belum dibuka/dikonfirmasi oleh admin.'; end if;
 select count(*) into occupied from pkl_private.registrations where quota_id=qid and status='active';
 if q.terisi_import+occupied>=q.kuota then raise exception 'Kuota tujuan sudah penuh. Pilihan lama tetap tersimpan.'; end if;
end; $$;

create function pkl_private.check_change(sid bigint,pid bigint,changes int) returns text
language plpgsql security definer set search_path='' as $$
declare pe pkl_private.periods; permission pkl_private.permissions; mode text;
begin
 select * into pe from pkl_private.periods where id=pid;
 select * into permission from pkl_private.permissions where student_id=sid and period_id=pid;
 if not pe.registration_open or (pe.deadline is not null and pe.deadline<=now()) then raise exception 'Periode ditutup atau melewati tenggat.'; end if;
 mode:=coalesce(nullif(permission.change_override,'inherit'),pe.change_mode);
 if mode='locked' then raise exception 'Pilihan dikunci. Hubungi admin untuk perubahan.'; end if;
 if changes>=pe.max_changes+coalesce(permission.extra_changes,0) then raise exception 'Batas perubahan telah tercapai.'; end if;
 return mode;
end; $$;

create function public.pkl_snapshot() returns jsonb language plpgsql security definer set search_path='' as $$
declare adm boolean; sid bigint; result jsonb;
begin
 if auth.uid() is null then raise exception 'Silakan login terlebih dahulu.'; end if;
 adm:=pkl_private.is_admin(); sid:=pkl_private.my_student_id();
 if not adm and sid is null then
   return jsonb_build_object('role','unregistered','email',(select email from auth.users where id=auth.uid()),'students','[]'::jsonb,'tempat_pkl','[]'::jsonb,'periods','[]'::jsonb,'quota_allocations','[]'::jsonb,'registrations','[]'::jsonb,'requests','[]'::jsonb,'permissions','[]'::jsonb,'audit','[]'::jsonb);
 end if;
 select jsonb_build_object(
  'role',case when adm then 'admin' else 'student' end, 'student_id',sid,
  'email',(select email from auth.users where id=auth.uid()),
  'students',coalesce((select jsonb_agg(to_jsonb(s) order by s.id) from pkl_private.students s where adm or s.id=sid),'[]'::jsonb),
  'tempat_pkl',coalesce((select jsonb_agg(to_jsonb(p) order by p.id) from pkl_private.places p where adm or p.jurusan=(select jurusan from pkl_private.students where id=sid)),'[]'::jsonb),
  'periods',coalesce((select jsonb_agg(to_jsonb(p) order by p.id) from pkl_private.periods p),'[]'::jsonb),
  'quota_allocations',coalesce((select jsonb_agg(to_jsonb(q)||jsonb_build_object('new_count',(select count(*) from pkl_private.registrations r where r.quota_id=q.id and r.status='active')) order by q.id) from pkl_private.quotas q join pkl_private.places p on p.id=q.tempat_id where adm or p.jurusan=(select jurusan from pkl_private.students where id=sid)),'[]'::jsonb),
  'registrations',coalesce((select jsonb_agg(to_jsonb(r) order by r.id) from pkl_private.registrations r where adm or r.student_id=sid),'[]'::jsonb),
  'requests',coalesce((select jsonb_agg(to_jsonb(r) order by r.id desc) from pkl_private.requests r where adm or r.student_id=sid),'[]'::jsonb),
  'permissions',coalesce((select jsonb_agg(to_jsonb(p)) from pkl_private.permissions p where adm or p.student_id=sid),'[]'::jsonb),
  'audit',coalesce((select jsonb_agg(to_jsonb(a) order by a.id desc) from (select * from pkl_private.audit where adm or student_id=sid order by id desc limit 200) a),'[]'::jsonb)
 ) into result;
 return result;
end; $$;

create function public.pkl_action(action text,payload jsonb default '{}') returns jsonb
language plpgsql security definer set search_path='' as $$
declare sid bigint; pid bigint; qid bigint; rid bigint; adm boolean; why text; mode text;
 r pkl_private.registrations; req pkl_private.requests; q pkl_private.quotas;
 pe pkl_private.periods; old_s pkl_private.students; cap int; base int; occupied int; rowdata jsonb;
begin
 if auth.uid() is null then raise exception 'Silakan login terlebih dahulu.'; end if;
 -- Serialize quota writes, settings writes, identity edits, reset and approvals.
 perform pg_catalog.pg_advisory_xact_lock(2712026);
 adm:=pkl_private.is_admin();
 if action like 'admin_%' and not adm then raise exception 'Akses admin diperlukan.'; end if;
 sid:=case when adm and action like 'admin_%' then nullif(payload->>'student_id','')::bigint else pkl_private.my_student_id() end;
 pid:=nullif(payload->>'period_id','')::bigint;
 qid:=nullif(payload->>'quota_id','')::bigint;
 why:=trim(coalesce(payload->>'reason',''));
 if action in ('choose','request_change') then
   if sid is null then raise exception 'Email belum terdaftar sebagai siswa aktif.'; end if;
   select * into q from pkl_private.quotas where id=qid;
   if not found then raise exception 'Tempat tidak ditemukan.'; end if;
   pid:=q.period_id;
   select * into r from pkl_private.registrations where student_id=sid and period_id=pid;
   if r.status='active' and r.quota_id=qid then return jsonb_build_object('message','Pilihan ini sudah tersimpan.'); end if;
   perform pkl_private.check_target(sid,qid,true);
   if r.status='active' then
     mode:=pkl_private.check_change(sid,pid,r.change_count);
     if mode='admin_approval' then
       if action<>'request_change' then raise exception 'Ajukan perubahan untuk persetujuan admin.'; end if;
       if length(why)<5 then raise exception 'Isi alasan perubahan minimal 5 karakter.'; end if;
       if exists(select 1 from pkl_private.requests where registration_id=r.id and status='pending') then raise exception 'Masih ada pengajuan perubahan yang menunggu.'; end if;
       insert into pkl_private.requests(registration_id,student_id,period_id,from_quota_id,target_quota_id,reason)
       values(r.id,sid,pid,r.quota_id,qid,why);
       perform pkl_private.log_event(sid,pid,'request_change',r.quota_id,qid,why);
       return jsonb_build_object('message','Pengajuan dikirim. Pilihan lama tetap aktif sampai disetujui.');
     end if;
     if action='request_change' then raise exception 'Mode perubahan langsung aktif. Gunakan simpan pilihan.'; end if;
     if exists(select 1 from pkl_private.requests where registration_id=r.id and status='pending') then raise exception 'Tarik pengajuan sebelumnya terlebih dahulu.'; end if;
     if length(why)<5 then raise exception 'Isi alasan perubahan minimal 5 karakter.'; end if;
   end if;
   insert into pkl_private.registrations(student_id,period_id,quota_id,status,change_count)
   values(sid,pid,qid,'active',0)
   on conflict(student_id,period_id) do update set quota_id=excluded.quota_id,status='active',
     change_count=pkl_private.registrations.change_count+case when pkl_private.registrations.status='active' then 1 else 0 end,updated_at=now();
   perform pkl_private.log_event(sid,pid,case when r.status='active' then 'change' else 'choose' end,r.quota_id,qid,coalesce(nullif(why,''),'Pendaftaran siswa'));
 elsif action='withdraw_request' then
   if sid is null then raise exception 'Siswa tidak ditemukan.'; end if;
   select * into req from pkl_private.requests where id=(payload->>'request_id')::bigint and student_id=sid and status='pending';
   if not found then raise exception 'Pengajuan aktif tidak ditemukan.'; end if;
   update pkl_private.requests set status='withdrawn',decided_at=now(),decided_by=auth.uid() where id=req.id;
   perform pkl_private.log_event(sid,req.period_id,'withdraw_request',req.from_quota_id,req.target_quota_id,'Ditarik oleh siswa');
 elsif action='admin_quota' then
   select * into q from pkl_private.quotas where id=qid;
   if not found then raise exception 'Kuota tidak ditemukan.'; end if;
   if length(why)<5 then raise exception 'Alasan perubahan minimal 5 karakter.'; end if;
   cap:=nullif(payload->>'kuota','')::int; base:=nullif(payload->>'terisi_import','')::int;
   if cap<0 or base<0 then raise exception 'Nilai kuota dan terisi tidak boleh negatif.'; end if;
   if coalesce((payload->>'import_confirmed')::boolean,false) and (cap is null or base is null) then raise exception 'Isi kuota dan saldo terisi sebelum konfirmasi.'; end if;
   select count(*) into occupied from pkl_private.registrations where quota_id=qid and status='active';
   if cap is not null and base is not null and cap<base+occupied and coalesce((payload->>'registration_open')::boolean,false) then raise exception 'Tidak dapat membuka alokasi yang melebihi kuota.'; end if;
   if cap is not null and base is not null and occupied>0 and cap<base+occupied then raise exception 'Kuota baru lebih kecil daripada total terisi. Pindahkan siswa dahulu.'; end if;
   update pkl_private.quotas set kuota=cap,terisi_import=base,
     import_confirmed=coalesce((payload->>'import_confirmed')::boolean,false),registration_open=coalesce((payload->>'registration_open')::boolean,false) where id=qid;
   perform pkl_private.log_event(null,q.period_id,'admin_quota',qid,qid,why,jsonb_build_object('before',to_jsonb(q),'after',payload));
 elsif action='admin_period' then
   select * into pe from pkl_private.periods where id=pid;
   if not found then raise exception 'Periode tidak ditemukan.'; end if;
   if length(why)<5 then raise exception 'Isi alasan minimal 5 karakter.'; end if;
   update pkl_private.periods set registration_open=(payload->>'registration_open')::boolean,
    change_mode=payload->>'change_mode',max_changes=(payload->>'max_changes')::int,
    deadline=nullif(payload->>'deadline','')::timestamptz where id=pid;
   perform pkl_private.log_event(null,pid,'admin_period',null,null,why,jsonb_build_object('before',to_jsonb(pe),'after',payload));
 elsif action='admin_permission' then
   if length(why)<5 then raise exception 'Isi alasan minimal 5 karakter.'; end if;
   insert into pkl_private.permissions(student_id,period_id,change_override,extra_changes)
   values(sid,pid,payload->>'change_override',(payload->>'extra_changes')::int)
   on conflict(student_id,period_id) do update set change_override=excluded.change_override,extra_changes=excluded.extra_changes;
   perform pkl_private.log_event(sid,pid,'admin_permission',null,null,why,payload);
 elsif action='admin_reset' then
   if length(why)<5 then raise exception 'Alasan reset minimal 5 karakter.'; end if;
   select * into r from pkl_private.registrations where student_id=sid and period_id=pid and status='active';
   if not found then raise exception 'Siswa belum memiliki pilihan aktif di periode ini.'; end if;
   update pkl_private.registrations set status='reset',updated_at=now() where id=r.id;
   update pkl_private.requests set status='withdrawn',decided_at=now(),decided_by=auth.uid() where registration_id=r.id and status='pending';
   perform pkl_private.log_event(sid,pid,'admin_reset',r.quota_id,null,why);
 elsif action='admin_move' then
   if length(why)<5 then raise exception 'Alasan pemindahan minimal 5 karakter.'; end if;
   select * into r from pkl_private.registrations where student_id=sid and period_id=pid and status='active';
   if not found then raise exception 'Pilihan aktif tidak ditemukan.'; end if;
   select * into q from pkl_private.quotas where id=qid;
   if q.period_id is distinct from pid then raise exception 'Gelombang tujuan berbeda.'; end if;
   if r.quota_id=qid then raise exception 'Tempat tujuan sama dengan pilihan saat ini.'; end if;
   perform pkl_private.check_target(sid,qid,false);
   update pkl_private.registrations set quota_id=qid,change_count=change_count+1,updated_at=now() where id=r.id;
   update pkl_private.requests set status='withdrawn',decided_at=now(),decided_by=auth.uid() where registration_id=r.id and status='pending';
   perform pkl_private.log_event(sid,pid,'admin_move',r.quota_id,qid,why);
 elsif action='admin_decide' then
   if length(why)<5 then raise exception 'Catatan keputusan minimal 5 karakter.'; end if;
   select * into req from pkl_private.requests where id=(payload->>'request_id')::bigint and status='pending';
   if not found then raise exception 'Pengajuan sudah diproses atau tidak ditemukan.'; end if;
   if coalesce((payload->>'approve')::boolean,false) then
     select * into r from pkl_private.registrations where id=req.registration_id;
     if r.status<>'active' or r.quota_id<>req.from_quota_id then raise exception 'Pilihan sudah berubah. Tolak pengajuan lama.'; end if;
     mode:=pkl_private.check_change(req.student_id,req.period_id,r.change_count);
     if mode<>'admin_approval' then raise exception 'Mode perubahan telah berubah. Tolak pengajuan lama dan arahkan siswa memilih kembali.'; end if;
     perform pkl_private.check_target(req.student_id,req.target_quota_id,true);
     update pkl_private.registrations set quota_id=req.target_quota_id,change_count=change_count+1,updated_at=now() where id=r.id;
   end if;
   update pkl_private.requests set status=case when (payload->>'approve')::boolean then 'approved' else 'rejected' end,decided_at=now(),decided_by=auth.uid() where id=req.id;
   perform pkl_private.log_event(req.student_id,req.period_id,case when (payload->>'approve')::boolean then 'approve' else 'reject' end,req.from_quota_id,req.target_quota_id,why);
 elsif action='admin_student' then
   if length(why)<5 then raise exception 'Isi alasan minimal 5 karakter.'; end if;
   if length(trim(payload->>'nama_lengkap'))<2 or length(trim(payload->>'nis'))<1 or (payload->>'email') not like '%@%' then raise exception 'Nama, NIS, dan email harus valid.'; end if;
   if sid is null then
     insert into pkl_private.students(nis,nama_lengkap,kelas,jurusan,email,is_dummy,active)
     values(trim(payload->>'nis'),trim(payload->>'nama_lengkap'),trim(payload->>'kelas'),payload->>'jurusan',lower(trim(payload->>'email')),false,true) returning id into sid;
   else
     select * into old_s from pkl_private.students where id=sid;
     if not found then raise exception 'Siswa tidak ditemukan.'; end if;
     if old_s.jurusan<>payload->>'jurusan' and exists(select 1 from pkl_private.registrations where student_id=sid and status='active') then raise exception 'Reset seluruh pilihan aktif sebelum mengubah jurusan.'; end if;
     update pkl_private.students set nis=trim(payload->>'nis'),nama_lengkap=trim(payload->>'nama_lengkap'),kelas=trim(payload->>'kelas'),
     jurusan=payload->>'jurusan',email=lower(trim(payload->>'email')),active=coalesce((payload->>'active')::boolean,true) where id=sid;
   end if;
   perform pkl_private.log_event(sid,null,'admin_student',null,null,why,jsonb_build_object('before',to_jsonb(old_s),'after',payload));
 else raise exception 'Aksi tidak dikenal.';
 end if;
 return jsonb_build_object('message','Perubahan berhasil disimpan.');
end; $$;

revoke all on all functions in schema pkl_private from public, anon, authenticated;
revoke all on function public.pkl_snapshot() from public, anon;
revoke all on function public.pkl_action(text,jsonb) from public, anon;
grant execute on function public.pkl_snapshot() to authenticated;
grant execute on function public.pkl_action(text,jsonb) to authenticated;
commit;
